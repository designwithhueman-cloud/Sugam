// Every tool a person can fix a finding in, and what Avara gives them there. One registry for the report and the landing page, so what the
// landing page promises is exactly what a report shows.
//   AI builders: a ready-to-paste prompt (element, measured problem, smallest change, how the builder checks it).
//   Visual editors: the selected editor's own steps (where to go, which setting, the value, how to preview).
//   Vercel: a question first (edit in v0, or in the project's source?), then the matching prompt or code.
//   Code: the change in the framework's own syntax and where it goes. "Copy patch" only for an evidence-backed edit (the selector was confirmed
//   to match only this element); otherwise "Copy example", and the DOM locator moves to Technical details.
// Built at render time from the stored fix (Element and Change lines, steps, and the code object), so older scans get every tool too.
