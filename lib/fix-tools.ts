type Code = { language: string; before: string; after: string; note?: string; example?: string };
export type ToolFix = {
  tool: Tool; intro: string; hint?: string; copyLabel: string; copyText: string;
  text?: string;                          // a prompt or a code block, shown as written
  steps?: string[];                       // editor steps
  code?: { label: string; text: string; before?: string };   // the snippet to apply (with the original markup, for an HTML edit)
  change?: string;                        // what to change, in words (every code option has it)
  where?: string;                         // where the code goes in this framework
  example?: boolean;                      // the code is an example: the scan did not confirm a selector for this exact element
  technical?: string;                     // the DOM locator, for Technical details
  route?: { question: string; options: { label: string; to: string }[] };
};

const bare = (p: string) => (p.includes('\n\n') ? p.slice(p.indexOf('\n\n') + 2) : p);
const line = (t: string, k: string) => new RegExp(`(?:^|\\n)${k}:\\s*([^\\n]+)`).exec(t)?.[1]?.trim() ?? '';
const nameIn = (element: string) => /“([^”]+)”/.exec(element)?.[1] ?? null;
const widthIn = (element: string) => /\((\d+)px(?: and (\d+)px)? wide\)/.exec(element);

/** The stored fix, read once: prompt body, its Element / Change lines, the check, the steps and the code. */
export function readFix(fixes: AvaraFix[]) {
  const p = fixes.find((f) => f.kind === 'prompt');
  const body = p ? bare(p.content) : '';
  const { prompt, verify } = splitFix(body);
  const manual = /Manual check:\s*(.+)$/.exec(verify)?.[1]?.trim() ?? '';
  const rescan = verify.replace(/\s*Manual check:.*$/, '').trim();
  let code: Code | null = null; const c = fixes.find((f) => f.kind === 'patch');
  if (c) { try { code = JSON.parse(c.content) as Code; } catch { code = null; } }
  const steps = (id: string) => { const s = fixes.find((f) => f.tool === id && f.kind === 'steps'); return s ? bulletLines(s.content) : null; };
  // Avara's own reason for not offering a patch ("…, so no code is given.") explains the Code tab; a builder or a reader of the change needs only the change.
  const clean = (t: string) => t.replace(/(^|\n)(Change:\s*)([^\n]*)/, (_m, a: string, b: string, c: string) => a + b + c.replace(/[^.]*\bso no code is given\.\s*/g, '').replace(/[^.]*\bThe selector above is a locator, not a patch\.\s*/g, ''));
  const p2 = clean(prompt);
  return { prompt: p2, element: line(p2, 'Element'), change: line(p2, 'Change'), rescan, manual, code, webflow: steps('webflow'), framer: steps('framer') };
}

/** How the builder itself checks the change: the condition Avara's rescan uses, at the same width, plus any manual check. */
export function builderCheck(rescan: string, manual: string, el = 'the element', width: string | null = null): string {
  const cond = /marks it Fixed only when (.+?)\.?$/.exec(rescan)?.[1]?.trim();
  const at = /\bat ((?:\d+px(?: and \d+px)?) wide)/.exec(rescan)?.[1];
  const useful = cond && !/^it passes there$/.test(cond);
  const first = useful ? `${at ? `At ${at}, ` : ''}${cond!.replace(/^it /, `${el} `)}.` : '';
  const out = [first && first.charAt(0).toUpperCase() + first.slice(1), manual].filter(Boolean).join(' ');
  return out || `${width ? `At ${width}px wide, ` : ''}${el} now shows the change above, and nothing else on the page moved.`.replace(/^./, (c) => c.toUpperCase());
}

const isCss = (c: Code | null) => !!c && c.language === 'css';
const toJsx = (html: string) => html.replace(/<!--\s*([\s\S]*?)\s*-->/g, '{/* $1 */}').replace(/\sclass=/g, ' className=').replace(/\sfor=/g, ' htmlFor=').replace(/\stabindex=/g, ' tabIndex=').replace(/\sreadonly(?=[\s>])/g, ' readOnly')
  .replace(/<(img|input|br|hr|meta|link|source)\b([^>]*?)\s*\/?>/g, '<$1$2 />');
/** Svelte scopes component styles: wrap each selector of the rule in :global() so it reaches markup Svelte did not render itself. */
export const svelteGlobal = (css: string) => css.replace(/(^|\n)([ \t]*)([^@{}\n][^{}\n]*?)\s*\{/g, (m, nl, ind, sel) => `${nl}${ind}${sel.split(',').map((s: string) => `:global(${s.trim()})`).join(', ')} {`);
const indent = (s: string) => s.split('\n').map((l) => `  ${l}`).join('\n');

// ---------- Editor steps from the actual change ----------
// The CSS change (patch or example) is read as declarations, and each one is mapped to the control that sets it in that editor, in the
// editor's own words. HTML changes map to the editor's element settings. Anything an editor has no control for goes through its
// custom-code setting, said plainly. Breakpoint: the width the problem was measured at.
type Decl = { prop: string; value: string };
/** The declarations of the first rule only: an example may add an alternative rule (a table wrapper), which is not the same element. */
export function declsOf(css: string): Decl[] {
  const first = /\{([^{}]*)\}/.exec(css.replace(/\/\*[\s\S]*?\*\//g, ''))?.[1] ?? '';
  return [...first.matchAll(/([a-z-]+)\s*:\s*([^;{}]+);/g)].map((m) => ({ prop: m[1], value: m[2].trim() }));
}
const attrsOf = (h: string) => new Map([...h.matchAll(/\s([a-z-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
/** Attributes the HTML change adds or changes, and a heading tag change. */
export function htmlChanges(before: string, after: string): { attr: string; value: string }[] {
  const b = attrsOf(before), a = attrsOf(after); const out = [...a].filter(([k, v]) => b.get(k) !== v && k !== 'class').map(([attr, value]) => ({ attr, value }));
  const tb = /^<\s*(h[1-6])/i.exec(before)?.[1], ta = /^<\s*(h[1-6])/i.exec(after)?.[1];
  if (tb && ta && tb !== ta) return [...out, { attr: 'tag', value: ta.toUpperCase() }];
  // A different element (a div that should be a button): the editor replaces the element; its type attribute comes with it.
  const eb = /^<\s*([a-z0-9-]+)/i.exec(before)?.[1]?.toLowerCase(), ea = /^<\s*([a-z0-9-]+)/i.exec(after)?.[1]?.toLowerCase();
  if (eb && ea && eb !== ea) return [{ attr: 'element', value: ea }];
  return out;
}
const targetOf = (css: string, el: string) => { const sel = /(^|\n)\s*([.#][\w-]+)\s*\{/.exec(css.replace(/\/\*[\s\S]*?\*\//g, ''))?.[2]; if (sel && !sel.startsWith('.your-') && /wider than the screen/.test(css)) return `the element with class ${sel.slice(1)} (it is wider than the screen)`; const ph = /\.your-([a-z-]+)/.exec(css)?.[1]; return ph === 'banner' ? `the bar that covers ${el}` : ph === 'container' ? `the container around ${el}` : ph === 'wide-element' || ph === 'table-wrapper' ? 'the element that is wider than the screen' : el; };
const cap = (x: string) => x.charAt(0).toUpperCase() + x.slice(1);

function webflowSteps(css: string, html: { attr: string; value: string }[], el: string, width: number | null, check: string): string[] | null {
  const d = declsOf(css); if (!d.length && !html.length) return null;
  const bp = width == null ? null : width <= 478 ? 'Mobile portrait' : width <= 767 ? 'Mobile landscape' : width <= 991 ? 'Tablet' : null;
  const out: string[] = []; const custom: string[] = [];
  if (bp) out.push(`In the top bar, switch to the ${bp} breakpoint, so the change applies only where the problem was measured (${width}px wide).`);
  out.push(`In the Navigator, select ${targetOf(css, el)}.`);
  const get = (p: string) => d.find((x) => x.prop === p)?.value;
  const size = [['min-width', 'Min W'], ['min-height', 'Min H'], ['max-width', 'Max W'], ['width', 'Width'], ['height', 'Height']].filter(([p]) => get(p)).map(([p, l]) => `${l} to ${get(p)}`);
  if (size.length) out.push(`In the Style panel, under Size, set ${size.join(' and ')}.`);
  if (get('position')) out.push(`In the Style panel, under Position, set Position to ${cap(get('position')!)}.`);
  if (get('display')) out.push(`In the Style panel, under Layout, set Display to ${/flex/.test(get('display')!) ? 'Flex' : /grid/.test(get('display')!) ? 'Grid' : cap(get('display')!)} (not None).`);
  if (get('overflow') || get('overflow-x')) out.push(`In the Style panel, under Size, set Overflow to ${cap((get('overflow') ?? get('overflow-x'))!)}.`);
  if (get('transform')) out.push('In the Style panel, under Effects, remove the 2D and 3D transforms on this element.');
  if (get('color')) out.push(`In the Style panel, under Typography, set Color to ${get('color')}.`);
  if (get('background-color')) out.push(`In the Style panel, under Backgrounds, set the color to ${get('background-color')}.`);
  for (const p of ['pointer-events', 'visibility']) if (get(p)) custom.push(`${p}: ${get(p)};`);
  for (const h of html) {
    if (h.attr === 'element') out.push(`Replace it with a ${h.value === 'a' ? 'Link Block' : 'Button'} element from the Add panel (A), move its content into it, and give it the same class.${h.value === 'button' ? ' If it goes to another page, use a Link Block and set its link instead.' : ''}`);
    else if (h.attr === 'alt') out.push(`Open Element settings (D) and set Alt text to ${h.value || '“” (decorative image)'}.`);
    else if (h.attr === 'tag') out.push(`Open Element settings (D) and change the heading Tag to ${h.value}.`);
    else out.push(`Open Element settings (D). Under Custom attributes, click + and add Name ${h.attr}, Value ${h.value}.`);
  }
  if (custom.length) out.push(`The Style panel has no control for ${custom.map((c) => c.split(':')[0]).join(' or ')}: in Page settings, under Custom code (Inside <head> tag), add <style>.your-class { ${custom.join(' ')} }</style>, using the element’s class.`);
  out.push(`Click Preview${bp ? ` at ${bp}` : ''} and check: ${check} Then publish.`);
  return out;
}
function framerSteps(css: string, html: { attr: string; value: string }[], el: string, width: number | null, check: string): string[] | null {
  const d = declsOf(css); if (!d.length && !html.length) return null;
  const phone = width != null && width <= 809;
  const out: string[] = []; const custom: string[] = [];
  if (phone) out.push(`At the top of the canvas, switch to the Phone breakpoint, so the change applies only where the problem was measured (${width}px wide).`);
  out.push(`In Layers, select ${targetOf(css, el)}.`);
  const get = (p: string) => d.find((x) => x.prop === p)?.value;
  const size = [['min-width', 'Min Width'], ['min-height', 'Min Height'], ['max-width', 'Max Width'], ['width', 'Width'], ['height', 'Height']].filter(([p]) => get(p)).map(([p, l]) => `${l} to ${get(p) === '100%' ? 'Fill' : get(p)}`);
  if (size.length) out.push(`In the properties panel, under Size, set ${size.join(' and ')}.`);
  if (get('position')) out.push(`In the properties panel, under Position, change it to ${get('position') === 'static' ? 'Relative' : cap(get('position')!)}.`);
  if (get('display') || get('visibility')) out.push('Make sure the layer is visible at this breakpoint (the eye icon in Layers is on).');
  if (get('overflow') || get('overflow-x')) out.push(`In the properties panel, set Overflow to ${/auto|scroll/.test((get('overflow') ?? get('overflow-x'))!) ? 'Scroll' : 'Visible'}.`);
  if (get('transform')) out.push('In the properties panel, under Transform, reset Offset, Rotate and Scale.');
  if (get('color')) out.push(`Set the text Color to ${get('color')}.`);
  if (get('background-color')) out.push(`Set Fill to ${get('background-color')}.`);
  if (get('pointer-events')) custom.push(`pointer-events: ${get('pointer-events')};`);
  for (const h of html) {
    if (h.attr === 'element') out.push('In the properties panel, under Link, add a link (the page or section it opens), so it becomes a real link that works with the keyboard.');
    else if (h.attr === 'alt') out.push(`In the image’s properties, set Alt Text to ${h.value || 'nothing (decorative image)'}.`);
    else if (h.attr === 'tag') out.push(`In the text properties, change the Tag to ${h.value}.`);
    else custom.push(`${h.attr}="${h.value}"`);
  }
  if (custom.length) out.push(`Framer has no field for ${custom.map((c) => c.split(/[:=]/)[0]).join(' or ')} on this layer: use the AI builder prompt in a Code Override for it, or add it in Site settings, under Custom Code.`);
  out.push(`Click Preview, resize to ${phone ? `${width}px` : 'the measured width'}, and check: ${check} Then publish.`);
  return out;
}

export function fixForTool(id: string, fixes: AvaraFix[]): ToolFix | null {
  const tool = toolById(id); if (!tool) return null;
  // The element as the scan named it: its label, or else its own description ("The icon button (.icon-btn) in the header").
  const f = readFix(fixes); const name = nameIn(f.element); const desc = f.element.split(/, (?:on desktop|on a phone)/)[0].replace(/^The /, 'the ');
  const el = name ? `“${name}”` : desc && desc.length < 90 ? desc : 'the element';
  const w = widthIn(f.element); const phone = w && Number(w[1]) <= 480;
  const check = builderCheck(f.rescan, f.manual, el, w ? w[1] : null);

  if (tool.group === 'ai') {
    const text = [f.prompt, `Check: ${check}`].filter(Boolean).join('\n');
    // The copy is the prompt alone: the tool's lead-in ("In Cursor, … search the codebase first") is advice for the person, shown above it.
    return { tool, intro: `Paste this into ${tool.name}`, hint: tool.prefix!.replace(/:$/, '.'), copyLabel: 'prompt', copyText: text, text };
  }

  if (tool.group === 'route') return {
    tool, intro: 'Vercel hosts the site. Where do you edit it?', copyLabel: '', copyText: '',
    route: { question: 'Where do you edit this site?', options: [{ label: 'In v0', to: 'v0' }, { label: 'In the project’s source', to: 'nextjs' }] },
  };

  const css = isCss(f.code) ? (f.code!.after || f.code!.example || '') : '';
  const preview = phone ? `Preview at phone width (${w![1]}px) and check: ${check}` : `Preview the page and check: ${check}`;

  if (tool.group === 'editor') {
    if (tool.id === 'shopify') {
      const steps = [
        'In Shopify admin, go to Online Store, then Themes, and click Customize on your live theme.',
        `Open the page with ${el}, then select the section that contains it in the left sidebar.`,
        css ? 'In that section’s settings, open Custom CSS and add the CSS below.' : `In that section’s settings, ${f.change.replace(/ Change nothing else\.?$/, '').replace(/^./, (c) => c.toLowerCase())}`,
        `Switch the preview to mobile with the phone icon at the top. ${preview.replace(/^Preview at phone width \(\d+px\) and check: |^Preview the page and check: /, 'Check: ')}`,
        'Click Save.',
      ];
      return { tool, intro: 'Follow these steps in Shopify', copyLabel: 'steps', copyText: steps.map((s, i) => `${i + 1}. ${s}`).join('\n') + (css ? `\n\n${css}` : ''), steps, code: css ? { label: f.code!.after ? 'CSS to add' : 'Example CSS (match the selector to your theme)', text: css } : undefined, example: !!css && !f.code!.after };
    }
    // Steps built from the actual change (declarations and attributes mapped to this editor's controls). The stored, rule-level steps are the
    // fallback when the fix carries no code; they are given the element's name.
    const html = f.code && (f.code.language === 'html' || f.code.language === 'jsx') ? htmlChanges(f.code.before, f.code.after || f.code.example || '') : [];
    const built = (tool.id === 'webflow' ? webflowSteps : framerSteps)(css, html, el, w ? Number(w[1]) : null, check);
    const base = built ?? ((tool.id === 'webflow' ? f.webflow : f.framer) ?? [`Select ${el}.`, f.change.replace(/ Change nothing else\.?$/, '')]).map((x) => (name ? x.replace(/^Select the (control|element|button|link|field|image)\b/i, `Select ${el}`) : x));
    const steps = built || /preview/i.test(base[base.length - 1] ?? '') ? base : [...base, preview.endsWith('.') ? preview : `${preview}`];
    return { tool, intro: `Follow these steps in ${tool.name}`, copyLabel: 'steps', copyText: steps.map((s, i) => `${i + 1}. ${s}`).join('\n'), steps };
  }

  // Code: the framework's own syntax, where it goes, and what to change in words.
  const c = f.code; const change = f.change.replace(/ Change nothing else\.?$/, '');
  const exact = !!c?.after; const exampleText = !exact ? (c?.example ?? '') : '';
  const technical = c ? (c.language === 'css' ? c.before : c.before) : undefined;
  if (c && c.language === 'css' && (c.after || c.example)) {
    const raw = c.after || c.example!;
    const where: Record<string, [string, string]> = {
      nextjs: ['Add this to app/globals.css (App Router) or styles/globals.css (Pages Router). If the element is styled with a CSS Module, put the same rule in that .module.css file.', raw],
      react: ['Add this to your global stylesheet, for example src/index.css or src/App.css.', raw],
      astro: ['Add this to the page or layout that renders the element, inside a global style block.', `<style is:global>\n${indent(raw)}\n</style>`],
      vue: ['Add this to the component’s <style> block. In a <style scoped> block, wrap the selector in :deep().', `<style>\n${indent(raw)}\n</style>`],
      svelte: ['Add this to the component’s <style> block. Svelte scopes styles, so the selector is wrapped in :global().', `<style>\n${indent(svelteGlobal(raw))}\n</style>`],
    };
    const [whereText, text] = where[tool.id];
    const ph = /\.your-[a-z-]+/.exec(raw)?.[0];
    return { tool, intro: exact ? 'Change this in your code' : 'An example to adapt in your code', copyLabel: exact ? 'patch' : 'example', copyText: text, change, where: exact ? whereText : `${whereText} ${ph ? `Replace ${ph} with the class that element has in your code.` : 'Adjust the selector to match that element in your code.'}`, code: { label: exact ? 'CSS' : 'Example CSS', text }, example: !exact, technical };
  }
  if (c && (c.language === 'html' || c.language === 'jsx') && (c.after || exampleText)) {
    const after = c.after || exampleText; const jsx = tool.id === 'nextjs' || tool.id === 'react';
    const text = jsx && c.language === 'html' ? toJsx(after) : after; const before = jsx && c.language === 'html' ? toJsx(c.before) : c.before;
    const file = { nextjs: 'the component (.tsx or .jsx) that renders it', react: 'the component (.tsx or .jsx) that renders it', astro: 'the .astro component that renders it', vue: 'the component’s <template>', svelte: 'the .svelte component that renders it' }[tool.id];
    return { tool, intro: exact ? 'Change this in your code' : 'An example to adapt in your code', copyLabel: exact ? 'patch' : 'example', copyText: text, change, where: `Find ${el} in ${file} and change its markup as shown.${/\[[^\]]+\]/.test(text) ? ' Replace the words in [brackets] with your own.' : ''}`, code: { label: exact ? (jsx ? 'JSX' : 'Markup') : jsx ? 'Example JSX' : 'Example markup', text, before }, example: !exact, technical: undefined };
  }
  // No snippet for this finding: say exactly what to change, and where to look.
  return { tool, intro: 'What to change in your code', copyLabel: 'change', copyText: `${f.element}\n${change}`, change, where: `Find ${el} in your ${tool.name} code${tool.id === 'svelte' ? ' (.svelte component)' : tool.id === 'astro' ? ' (.astro component)' : tool.id === 'vue' ? ' (component template and styles)' : ' (the component that renders it, and its styles)'} and make this change.`, technical };
}

/** A stored FixSet (accessibility issues) in the same shape as a recommendation's fixes, so every surface uses one fix view. */
export function fixesFromSet(f: { aiPrompt: Record<string, string>; noCode: { framer: string[]; webflow: string[] }; code: unknown } | null | undefined): AvaraFix[] {
  if (!f) return [];
  return [...Object.entries(f.aiPrompt).map(([tool, content]) => ({ tool, kind: 'prompt', content })), { tool: 'framer', kind: 'steps', content: f.noCode.framer.join('\n') }, { tool: 'webflow', kind: 'steps', content: f.noCode.webflow.join('\n') }, { tool: 'code', kind: 'patch', content: JSON.stringify(f.code) }];
}
